export const normalizeHelp = (value) =>
  String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase('pt-BR');
export function searchHelp(query, category = 'all') {
  const terms = normalizeHelp(query).trim().split(/\s+/).filter(Boolean);
  return helpArticles.filter(
    (article) =>
      (category === 'all' || article.category === category) &&
      terms.every((term) =>
        normalizeHelp(
          [
            article.title,
            article.summary,
            ...article.steps,
            ...article.notes,
            ...article.tags,
          ].join(' '),
        ).includes(term),
      ),
  );
}
